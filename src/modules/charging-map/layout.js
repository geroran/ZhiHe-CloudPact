export const LAYOUT_ROW_COUNT = LAYOUT.length;
export const LAYOUT_COLUMN_COUNT = 15;
export const PORT_CELLS = LAYOUT.flat().filter((cell) => cell.type === "port");
export const LAYOUT_PORT_COUNT = PORT_CELLS.length;
