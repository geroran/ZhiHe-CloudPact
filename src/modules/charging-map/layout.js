const PORT_TOKEN = /^(\d+)-(\d+)$/;

/**
 * 将行文本解析为单元格对象。端口 id 原样保留，过道文字原样保留。
 * @returns {Array<Array<{type: 'port', id: string, deviceNo: number, portNo: number, label: string}
 *   | {type: 'path', label: string, accent: boolean}>>}
 */
export function parseLayout(raw = RAW_LAYOUT) {
  const rows = raw
    .split("\n")
    .map((line) => line.trim())
    .filter(Boolean);

  const seen = new Set();

  return rows.map((line, rowIndex) => {
    const tokens = line.split(/\s+/);
    if (tokens.length !== 15) {
      throw new Error(`布局第 ${rowIndex + 1} 行有 ${tokens.length} 格，应为 15 格`);
    }

    return tokens.map((token) => {
      const match = PORT_TOKEN.exec(token);
      if (match) {
        if (seen.has(token)) {
          throw new Error(`布局端口 ID 重复：${token}`);
        }
        seen.add(token);
        return {
          type: "port",
          id: token,
          deviceNo: Number(match[1]),
          portNo: Number(match[2]),
          label: match[2],
        };
      }

      return {
        type: "path",
        label: token === "-" ? "" : token,
        accent: token === "入口",
      };
    });
  });
}

